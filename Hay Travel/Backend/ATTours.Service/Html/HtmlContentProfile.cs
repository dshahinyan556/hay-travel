namespace ATTours.BusinessServices.Html
{
    // Профиль rich-контента: «какой набор правил применять к этому тексту». Профиль — часть
    // публичной сигнатуры RichHtmlSanitizer.Sanitize, зафиксированной до появления второго
    // потребителя, чтобы подключение описаний туров правило таблицу политик, а не все вызовы
    // (ADR 026, решение 2).
    //
    // RichContent сегодня отображается на ту же запись политики, что и EmailBody: наборы
    // идентичны, а копия allow-list'а «на будущее» — это второй источник правды.
    public enum HtmlContentProfile
    {
        // Тело шаблона письма (раздел «Настройки уведомлений»).
        EmailBody = 1,

        // Описания туров/мест на публичном сайте (фаза 2, пока не подключён ни к одному вызову).
        RichContent = 2
    }
}
