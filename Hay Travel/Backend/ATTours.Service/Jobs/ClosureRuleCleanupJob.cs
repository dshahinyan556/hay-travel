using ATTours.Common.Entities;
using ATTours.Common.Enums;
using ATTours.Common.Infrastructure.Jobs;
using ATTours.Common.Infrastructure.Time;
using ATTours.Common.Settings;
using Microsoft.EntityFrameworkCore;

namespace ATTours.BusinessServices.Jobs
{
    // Уборка истёкших правил закрытия (решение Р6 от 2026-08-29). У таблицы ClosureRule
    // уборщика не было вовсе, и до потуровых правил это было терпимо: строки заводил
    // руками админ, их были десятки. Р4 изменил порядок величин — TourDateAutoClosureJob
    // материализует правило на КАЖДЫЙ продукт и КАЖДЫЙ день окна, то есть таблица растёт
    // как «продукты × дни» и не убывает никогда.
    //
    // Удаление, а не архивирование: правило с прошедшей датой не влияет ни на одно решение
    // (резолвер спрашивают только про сегодня и вперёд), объяснять по нему уже нечего —
    // день, который оно закрывало, прошёл. Ретеншен-параметра у задачи сознательно нет
    // (решение Давида): «истёк = удалён», окна снисхождения не предусмотрено, поэтому и
    // parameterKeys в каталоге пуст.
    //
    // Удаляются и ручные правила, и IsAutoGenerated: истёкшее правило мертво независимо от
    // того, кто его завёл. Разделять их значило бы копить ровно тот же мусор, только
    // медленнее.
    public class ClosureRuleCleanupJob : TourRepositoryCoreBase<ClosureRule>, IBackgroundJobHandler
    {
        // Размер одного DELETE — тот же приём и то же значение, что у
        // LoginHistoryCleanupJob: без ограничения первый прогон после накопления годового
        // хвоста держал бы блокировки на всей таблице и раздувал лог транзакций.
        private const int BatchSize = 1000;

        // Потолок одного прогона. Задача ежедневная: если хвост длиннее — его доберут
        // следующие прогоны, спешить некуда, а вот занимать базу на полчаса ради уборки
        // нельзя.
        private const int MaxBatchesPerExecution = 50;

        public ClosureRuleCleanupJob() : base(CommonSettings.Instance.ATToursConnectionString) { }

        public async Task<JobRunResult> ExecuteAsync(JobExecutionContext context, CancellationToken cancellationToken)
        {
            // «Сегодня» — по армянскому времени, как и у остальных задач, работающих с
            // календарным днём тура: в интервале 20:00-24:00 UTC серверная дата уже
            // завтрашняя, и по ней уборщик снёс бы правило на день, который в Ереване ещё
            // не начался.
            var today = ArmeniaTimeZone.TodayInArmenia(DateTime.UtcNow);
            var deleted = 0;

            for (var batch = 0; batch < MaxBatchesPerExecution; batch++)
            {
                cancellationToken.ThrowIfCancellationRequested();

                // Сначала пачка Id, потом удаление по ним — Take внутри ExecuteDelete
                // провайдер выражать не обязан, а два дешёвых запроса дают предсказуемый
                // SQL и гарантированно ограниченный батч (тот же приём, что в
                // LoginHistoryCleanupJob).
                //
                // Порядок по Id, а не по дате: критерий истечения смотрит на РАЗНЫЕ колонки
                // у разных типов правил (Date у точечного, EffectiveTo у недельного), и
                // общего поля для сортировки у них нет. Id монотонен и стабилен, а для
                // батчинга важна только стабильность выборки.
                var expiredIds = await Context.Set<ClosureRule>()
                    .AsNoTracking()
                    .Where(rule =>
                        // Точечное правило истекло, когда его день прошёл. EffectiveFrom/To
                        // здесь НАМЕРЕННО не смотрим, хотя валидация формы их у SpecificDate
                        // и не запрещает (ClosureRuleValidationService.ValidateShape следит
                        // только за парой Date/DayOfWeek), то есть строка с обоими
                        // заполненными полями теоретически возможна. Причина: резолвер к
                        // точечному правилу границы не применяет вовсе
                        // (ClosureRuleResolver.IsApplicable — «точечная дата адресует день
                        // сама»), значит единственное, что определяет его жизнь, это Date.
                        // Учитывать здесь EffectiveTo значило бы удалять по критерию,
                        // который на поведение правила не влияет.
                        (rule.Type == ClosureRuleType.SpecificDate && rule.Date < today)

                        // Недельное правило истекает только при заданной верхней границе.
                        // Weekly без EffectiveTo — бессрочное («по понедельникам не
                        // работаем»), оно не истекает никогда и уборщика не касается.
                        || (rule.Type == ClosureRuleType.Weekly
                            && rule.EffectiveTo != null
                            && rule.EffectiveTo < today))
                    .OrderBy(rule => rule.Id)
                    .Select(rule => rule.Id)
                    .Take(BatchSize)
                    .ToListAsync(cancellationToken);

                if (expiredIds.Count == 0)
                    break;

                deleted += await Context.Set<ClosureRule>()
                    .Where(rule => expiredIds.Contains(rule.Id))
                    .ExecuteDeleteAsync(cancellationToken);
            }

            return JobRunResult.Succeeded(deleted,
                $"Удалено истёкших правил закрытия: {deleted} (истёкшими считаются точечные до {today:dd.MM.yyyy} " +
                $"и недельные, срок действия которых закончился раньше этой даты).");
        }
    }
}
