namespace ATTours.Common.Enums
{
    // Каналы, по которым КОНКРЕТНЫЙ пользователь согласен получать служебные уведомления
    // (личные предпочтения, 2026-08-29). Флаги, а не одиночное значение: каналы
    // складываются, человек может хотеть и письмо, и Telegram сразу.
    //
    // Отдельно от NotificationPlatform, хотя числа совпадают намеренно: тот enum —
    // одиночный канал ОДНОЙ настроенной рассылки в админке (NotificationRecipient), этот —
    // множество каналов одного пользователя. Смешивать их в один тип нельзя: [Flags] на
    // NotificationPlatform сделал бы валидным значение Email|Telegram там, где адресат
    // выбирает ровно один канал.
    //
    // None существует только как нейтральный элемент побитовых операций: сохранить его в
    // User.NotificationChannels нельзя (см. UserPreferencesValidationService) — иначе
    // человек перестал бы узнавать о собственном заказе.
    [Flags]
    public enum NotificationChannelFlags
    {
        None = 0,
        Email = 1,
        Telegram = 2
    }
}
