namespace ATTours.Common.Enums
{
    // Исход одного прогона фоновой задачи. Общий enum для строки истории
    // (ScheduledJobRun.Status) и для результата хендлера (JobRunResult.Status) —
    // второго почти-такого-же enum'а сознательно нет: расхождение между «что записали
    // в лог» и «что вернул хендлер» было бы источником вечных ручных маппингов.
    public enum JobRunStatus
    {
        // Строка истории создаётся ДО вызова хендлера — иначе упавший процесс не оставил бы
        // о прогоне вообще никакого следа. Хендлер этот статус не возвращает никогда:
        // JobRunResult умеет только три терминальных исхода ниже.
        Running = 1,
        Succeeded = 2,
        // Задача отработала штатно, но делать было нечего или условия запуска не выполнены
        // (например нарушен инвариант конфига). Не ошибка, но и не успех — админ должен
        // видеть разницу.
        Skipped = 3,
        Failed = 4
    }
}
