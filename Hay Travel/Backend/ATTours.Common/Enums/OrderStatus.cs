namespace ATTours.Common.Enums
{
    // Жизненный цикл заказа (переделка B14, 2026-08-16): семь статусов вместо трёх, под
    // мульти-строчные заказы и ручной флоу назначения исполнителей. На проводе едет числом.
    //
    // Что считается «занимающим календарь» (OrderCalendarInfo) — все статусы, КРОМЕ Rejected:
    // рабочая гипотеза (не подтверждена Давидом явно), см. checklist-orders-redesign.txt.
    public enum OrderStatus
    {
        // Только что создан (бронь с сайта ИЛИ вручную в админке), ни одна строка не требует
        // предоплаты. Начальный статус, если PendingPayment не применяется (см. ниже).
        Open = 1,
        // На удержании: редактирование строк отключено, доступно только удаление.
        // Обратный переход — снова Open/тот статус, с которого поставили на Hold.
        Hold = 2,
        // Одобрен администратором.
        Approved = 3,
        // Отклонён. Редактирование недоступно, доступно только удаление. RejectReason — почему.
        Rejected = 4,
        // Одобрен и по нему проставлен процент предоплаты на строки — готов к назначению
        // исполнителей.
        ReadyForAssignment = 5,
        // Создан и хотя бы одна строка требует предоплаты (RequiresPrepayment) — ждёт её
        // поступления, прежде чем перейти дальше по флоу.
        PendingPayment = 6,
        // Выполнен (действие "Завершить").
        Completed = 7
    }
}
