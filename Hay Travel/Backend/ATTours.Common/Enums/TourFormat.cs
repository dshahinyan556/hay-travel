namespace ATTours.Common.Enums
{
    // Формат проведения продукта (батч «Трансферы + формат», 2026-08-29). Есть только у
    // тура/экскурсии; у трансфера (TourType.Transfer) поле не заполняется — null.
    public enum TourFormat
    {
        // Текущее (историческое) поведение цены: фикс за группу + тирная наценка по числу
        // гостей 1-4 / 5-6 / 7+ (на 7+ цена скрыта, «по запросу»).
        Individual = 1,
        // Цена ЗА ЧЕЛОВЕКА × количество гостей, без тиров и без скрытия цены.
        // Ограничитель — свободные места на пару (дата + время старта), см. Tour.GroupCapacity.
        Group = 2,
        // Продукт продаётся в обоих форматах; какой именно — выбирает клиент при бронировании
        // (снапшот выбора уезжает в OrderLine.Format).
        Both = 3
    }
}
