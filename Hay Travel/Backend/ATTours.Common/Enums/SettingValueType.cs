    {
        Text = 1,
        MultilineText = 2,
        Url = 3,
        ImageUrl = 4,
        // Значение — один id из фиксированного набора опций (Options в метаданных ключа),
        // рендерится в админке как выпадающий список. Тип хранения по-прежнему строка.
        Select = 5,
        // Целое число (часы/дни/лимиты). Появился ради операционных настроек фоновых
        // задач: описать их Text-ом означало бы пускать в БД «24 часа» вместо «24», а
        // потребитель (джоба) читает значение int.TryParse и молча падал бы на дефолт.
        // Хранение по-прежнему строка — общий инвариант всех настроек не ломается.
        Number = 6,
    }
}
