namespace ATTours.Common.Constants
{
    // Доменные лимиты заказа. Вынесены в именованную константу сознательно: то же число
    // держит у себя фронтовая корзина (`MAX_CART_ITEMS`, spec 008), и магическое «10» в двух
    // местах гарантированно разъедется. TS и C# не делят код в этом репозитории — меняешь
    // лимит здесь, меняй и там.
    public static class OrderLimits
    {
        // Максимум позиций в одном чекауте корзины (ADR 025). Превышение — плоская ошибка
        // формы запроса GlobalErrorCode.OrderTooManyLines (2032), не пер-строчная.
        public const int MaxOrderLines = 10;

        // Максимум гостей в ОДНОЙ строке брони продукта (тур, экскурсия, предопределённый
        // трансфер). Зеркало фронтового MAX_GUESTS (shared/booking/guests.ts) — решение 0.29:
        // фронтовый clamp это UX, а не защита от прямого запроса к API.
        //
        // К кастомной заявке на трансфер НЕ применяется сознательно: по решению 0.14 группа,
        // которая не влезает ни в один класс авто, как раз и уходит в заявку без цены —
        // упереться там в тот же потолок значило бы запретить ровно тот сценарий, ради
        // которого заявка существует.
        //
        // Админская строка заказа (OrderLineService) тоже не ограничена: у её формы свой,
        // намеренно другой потолок (AddLineModal.MAX_GUESTS = 99), и OrderValidationService
        // по этому пути не запускается.
        public const int MaxGuestsPerLine = 16;
    }
}
