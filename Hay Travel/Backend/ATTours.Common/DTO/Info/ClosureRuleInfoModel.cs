using ATTours.Common.Enums;

namespace ATTours.Common.DTO.Info
{
    // Чтение правил закрытия для админки: плоская проекция ClosureRule 1:1.
    // Публичный сайт правил не видит — ему отдаётся уже материализованный список
    // закрытых дат (GET api/Availability/GetClosedDates).
    public class ClosureRuleInfoModel
    {
        public int Id { get; set; }
        public int? TourId { get; set; }
        // Область «все продукты этого типа» (решение 0.27): взаимоисключима с TourId,
        // оба null = глобальное правило.
        public TourType? TourType { get; set; }
        public ClosureRuleType Type { get; set; }
        public ClosureAction Action { get; set; }
        public DateOnly? Date { get; set; }
        public DayOfWeek? DayOfWeek { get; set; }
        public DateOnly? EffectiveFrom { get; set; }
        public DateOnly? EffectiveTo { get; set; }
        public string Reason { get; set; }
        // Правила одного CreateRules-вызова делят один BatchId — экран «Блокировки» группирует
        // по нему. null у правил, созданных до этой колонки, и у одиночных toggle-закрытий из
        // старых клиентов (тоже проходят через CreateRules, так что в норме тоже не null).
        public Guid? BatchId { get; set; }
        // Строку завёл планировщик автозакрытия, а не человек. Едет наружу, чтобы
        // админ-календарь мог отличить её от ручной блокировки и не предлагал «отменить»
        // то, что планировщик создаст заново на следующем тике.
        public bool IsAutoGenerated { get; set; }
    }
}
