using ATTours.Common.Enums;

namespace ATTours.Common.DTO.Info
{
    // Один настраиваемый параметр фоновой задачи (порог/ретеншен) вместе с его текущим
    // значением. Физически значения живут в SiteSetting (ADR 002), но экран «Джобы»
    // правит их прямо на карточке задачи, поэтому они едут вместе с задачей: иначе
    // экрану пришлось бы делать второй запрос к api/SiteSettings/GetAll — а тот гейтится
    // правом settings:View, которого у роли «джобы» может не быть.
    public class JobParameterInfoModel
    {
        // Ключ настройки (например booking.autoCloseLeadTimeHours) — он же ключ в теле
        // PATCH api/Jobs/{key}/Parameters.
        public string Key { get; set; }

        // Человекочитаемая подпись из каталога настроек. Сейчас всегда null:
        // SiteSettingDefinition такого поля не объявляет, а придумывать текст на бэкенде
        // нельзя — он разъехался бы с подписями экрана «Настройки сайта». Поле оставлено
        // в контракте, чтобы подпись поехала сюда сама, как только появится в каталоге.
        public string DisplayName { get; set; }

        // Текущее значение строкой — ровно в том виде, в каком его хранит SiteSetting
        // (и в каком его принимает PATCH). Никогда не null: ключ без сохранённой строки
        // отдаёт дефолт каталога.
        public string Value { get; set; }

        // Тип значения из каталога настроек: экран рисует поле по нему (число/текст/
        // выбор), не зашивая тип конкретного ключа.
        public SettingValueType ValueType { get; set; }
    }
}
