namespace ATTours.Common.DTO.Info
{
    // Карточка фоновой задачи для экрана «Джобы»: неизменяемые метаданные из
    // BackgroundJobCatalog + изменяемое состояние из ScheduledJob + последний прогон из
    // ScheduledJobRun. Три источника сшивает ScheduledJobInfo, а не фронт — иначе экрану
    // пришлось бы знать состав каталога, которого он не видит.
    public class ScheduledJobInfoModel
    {
        // Ключ из каталога: и идентичность строки, и сегмент маршрута (api/Jobs/{key}/Run).
        public string Key { get; set; }

        public string DisplayName { get; set; }

        public bool IsEnabled { get; set; }

        // Эффективное расписание: переопределение из админки, а если его нет — дефолт
        // каталога. Именно по нему работает планировщик.
        public string CronExpression { get; set; }

        // Дефолт из кода. Едет наружу, чтобы экран мог показать «изменено относительно
        // умолчания» и предложить сброс, не угадывая исходное значение.
        public string DefaultCronExpression { get; set; }

        // Есть незакрытый прогон (FinishedAtUtc == null) — кнопка «Запустить сейчас»
        // блокируется ещё во фронте, а не только ответом 409.
        public bool IsRunning { get; set; }

        // Ближайший плановый запуск по эффективному расписанию. null у выключенной задачи:
        // она снята с расписания планировщика, и следующего запуска у неё нет.
        public DateTime? NextRunAtUtc { get; set; }

        // Кто-то менял рубильник/расписание из админки. null — задачу не трогали с момента
        // автосоздания строки реестра.
        public DateTime? UpdatedAtUtc { get; set; }

        // null, если задача не запускалась ни разу (в том числе сразу после деплоя).
        public ScheduledJobRunInfoModel LastRun { get; set; }

        // Настраиваемые параметры задачи (пороги/ретеншены) вместе с текущими значениями.
        // Раньше здесь были только ключи (ParameterKeys) и экран отправлял админа в
        // «Настройки сайта»; теперь параметры редактируются прямо на карточке задачи,
        // поэтому одних ключей мало — нужны значения и тип поля. Список ключей выводится
        // из этого же набора, отдельного поля под него нет.
        public List<JobParameterInfoModel> Parameters { get; set; } = [];
    }
}
