namespace ATTours.Common.DTO.Request
{
    // Снятие исполнителя — отдельная модель, а не Assign с nullable-полями: у назначения
    // роль обязательна (инвариант «назначение всегда с ролью»), и размывать его ради
    // обратной операции нельзя.
    //
    // Флага SendEmail здесь нет: отправку письма о снятии решает только рубильник канала
    // события order.unassign_employee.
    public class OrderUnassignEmployeeModel
    {
        public int OrderId { get; set; }

        // null = все строки заказа (bulk-семантика сохраняется).
        public int? LineId { get; set; }

        // null = снять ВСЕХ исполнителей с целевых строк (действие «снять исполнителя»
        // со строки целиком); задан = снять только этого человека. Один параметр покрывает
        // оба случая — иначе фронту пришлось бы слать N вызовов по числу исполнителей.
        public int? EmployeeId { get; set; }
    }
}
