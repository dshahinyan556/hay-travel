namespace ATTours.Common.DTO.Request
{
    // Правка одной строки заказа админом: предоплата и — с батча «Трансферы + формат»
    // (2026-08-29) — цена строки-заявки. "Детали для выполнения" (место встречи / навигатор /
    // комментарий) переехали на исполнителя — их правит OrderLineEmployeeUpdateModel
    // (редизайн 2026-08-23).
    //
    // Назначение исполнителя — отдельный эндпоинт (OrderAssignEmployeeModel), т.к. у него
    // своя bulk-логика ("на все строки").
    public class OrderLineUpdateModel
    {
        public int Id { get; set; }
        public bool RequiresPrepayment { get; set; }
        public decimal PrepaymentAmount { get; set; }

        // Цена, которую менеджер согласовал по кастомной заявке (решение 0.11: заявка
        // приходит без цены, сумму проставляют вручную). null — «не трогать сумму», ноль —
        // осмысленное значение («пока не согласована»), поэтому поле nullable, а не 0.
        //
        // Работает ТОЛЬКО на строке-заявке: у строки по продукту сумма — снапшот расчёта
        // (ADR 019), и переписать её руками нельзя (400 OrderNotEditable), иначе итог заказа
        // перестал бы соответствовать цене продукта.
        public decimal? LineTotal { get; set; }
    }
}
