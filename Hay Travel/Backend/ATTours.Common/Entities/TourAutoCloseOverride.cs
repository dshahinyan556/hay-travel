using ATTours.Common.Infrastructure.Abstractions;
using ATTours.Common.Infrastructure.EntityConfiguration;
using Microsoft.EntityFrameworkCore;

namespace ATTours.Common.Entities
{
    // Исключение из глобального порога автозакрытия для ОДНОГО продукта (батч 2026-08-29):
    // «Вайоц Дзор закрывается за 8 часов, а не за 36, как все остальные». Глобальное
    // значение остаётся в SiteSetting (booking.autoCloseLeadTimeHours) — здесь лежат только
    // отклонения от него, поэтому строк у таблицы ровно столько, сколько исключений завёл
    // админ, а не по строке на каждый продукт каталога.
    //
    // Почему отдельная сущность, а не колонка на Tour: значение принадлежит экрану
    // «Автозакрытие дат», а не форме продукта, и правится там же, где глобальный порог.
    // Практическая причина не менее важна: TourUpdateService копирует скаляры тура ВРУЧНУЮ,
    // поэтому колонка на Tour, которой нет в форме продукта, затиралась бы первым же
    // сохранением тура из админки.
    //
    // Мультиязычности нет и быть не может: это число часов, а не контент.
    [EntityTypeConfiguration(typeof(TourAutoCloseOverrideConfiguration))]
    public class TourAutoCloseOverride : EntityBase
    {
        // Продукт, для которого действует исключение. Уникален: два разных порога на один
        // продукт — это не два правила, а противоречие (см. конфигурацию).
        public int TourId { get; set; }
        public Tour Tour { get; set; }

        // Часы до самого позднего старта дня, за которые день перестаёт продаваться.
        // Строго положительное (TourAutoCloseOverrideValidationService): «ноль» и «минус»
        // означали бы «порог выключен», а выключенное исключение — это отсутствие строки,
        // а не строка с нулём. Иначе на экране появились бы два способа сказать одно и то же.
        public int LeadTimeHours { get; set; }
    }
}
