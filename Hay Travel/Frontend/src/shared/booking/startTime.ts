/**
 * Время старта продукта — одна каноничная форма на весь фронтенд: `HH:mm` (решение 0.21).
 *
 * На проводе форм две, и обе не наши:
 *  - бэк отдаёт `TimeOnly` как `"HH:mm:ss"` (System.Text.Json) — так приходят и
 *    `TourStartTimeInfoModel.time`, и `TourGroupSeatsSlotModel.startTime`;
 *  - бэк принимает `TimeOnly` — отправляем `"HH:mm:ss"`, а не `"HH:mm"`, чтобы не зависеть от
 *    того, насколько снисходителен парсер конкретной версии рантайма.
 *
 * Внутри фронта время живёт ТОЛЬКО как `HH:mm`: это же значение показывается посетителю,
 * складывается в localStorage корзины и участвует в идентификаторе позиции. Одна форма — одно
 * сравнение; иначе «09:00» и «09:00:00» разъехались бы в ключах корзины и в поиске слота.
 *
 * `Date` здесь не появляется намеренно — по той же причине, по которой даты в проекте это
 * строки `YYYY-MM-DD` (см. `shared/types/booking.ts`): у времени старта нет ни дня, ни
 * таймзоны, и превращать его в момент значило бы выдумать и то, и другое.
 */

/** `HH:mm` с ведущими нулями, часы 00-23. */
const DISPLAY_TIME = /^([01]\d|2[0-3]):[0-5]\d$/

/**
 * `"09:00:00"` / `"09:00"` → `"09:00"`. Пустая строка — «времени нет»: у продукта, созданного
 * до батча (миграция посеяла времена не всем) или у мусора в localStorage. Вызывающий сам
 * решает, что с этим делать, — здесь мы не подставляем ничего «по умолчанию».
 */
export function toDisplayTime(wireTime: string): string {
  const trimmed = wireTime.slice(0, 5)
  return DISPLAY_TIME.test(trimmed) ? trimmed : ''
}

/** `"09:00"` → `"09:00:00"` для тела запроса. Невалидный вход даёт `null`, а не «00:00:00»:
 * молча забронировать полночь — худший исход из возможных. */
export function toWireTime(displayTime: string): string | null {
  return DISPLAY_TIME.test(displayTime) ? `${displayTime}:00` : null
}

/** Валидно ли значение как `HH:mm`. */
export function isDisplayTime(value: string): boolean {
  return DISPLAY_TIME.test(value)
}
