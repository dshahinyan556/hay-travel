/**
 * Строка промежуточной остановки в конструкторе заявки.
 *
 * Живёт в `lib`, а не рядом с редактором, по одной причине: у неё собственный `id`, и завод этого
 * id — не разметка, а правило. dnd-kit адресует элементы ИМЕННО по id, поэтому индекс или текст в
 * этой роли недопустимы: две пустые (или две одинаковые) остановки схлопнулись бы в один ключ, и
 * список сломался бы ровно в самом обычном сценарии — «добавил две строки, заполняю по очереди».
 */

export interface RouteStop {
  id: string
  text: string
}

let stopSeq = 0

/** Модульный счётчик, а не `crypto.randomUUID`: id живёт только в памяти открытой формы — в
 * черновике `localStorage` лежит голый текст, — и уникальности в пределах вкладки достаточно. */
export function createRouteStop(text = ''): RouteStop {
  stopSeq += 1
  return { id: `stop-${stopSeq}`, text }
}
