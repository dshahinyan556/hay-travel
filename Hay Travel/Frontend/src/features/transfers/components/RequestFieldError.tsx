import { AlertIcon } from '@/shared/ui/icons'

/**
 * Сообщение об ошибке ПОД КОНКРЕТНЫМ ПОЛЕМ.
 *
 * Мастер не имеет права собирать претензии в общий список внизу шага: список заставляет искать,
 * какое из шести полей он имеет в виду. Поэтому одна и та же строка «иконка + текст» стоит ровно
 * там, где ошибку можно исправить, и один компонент на все поля гарантирует, что она везде
 * выглядит одинаково.
 *
 * `role="alert"` НЕ ставится: ошибки появляются пачкой по нажатию «Далее», и пять одновременных
 * alert'ов скринридер зачитает подряд, перебивая сам себя. Вместо этого экран переводит фокус на
 * первое поле с ошибкой — оно помечено `aria-invalid` и связано с этим текстом.
 */
export function RequestFieldError({ id, children }: { id?: string; children: string }) {
  return (
    <p id={id} className="mt-1.5 flex items-start gap-1.5 text-[12.5px] leading-snug text-danger">
      <span className="mt-0.5 shrink-0">
        <AlertIcon size={13} />
      </span>
      {children}
    </p>
  )
}
